// ============================================================ Assistant

interface Turn {
  id: number
  q: string
  r?: IntelResponse
}

export function AssistantPage() {
  usePage('Intelligence Assistant', [{ label: 'Security Intelligence' }, { label: 'Intelligence Assistant' }])
  const [params, setParams] = useSearchParams()
  const navigate = useNavigate()
  const setSearchOpen = useUiStore((s) => s.setSearchOpen)
  const [turns, setTurns] = React.useState<Turn[]>(() => {
    try {
      return JSON.parse(sessionStorage.getItem('dosafe-assistant') ?? '[]')
    } catch {
      return []
    }
  })
  const [q, setQ] = React.useState('')
  const [busy, setBusy] = React.useState(false)
  const endRef = React.useRef<HTMLDivElement>(null)
  const turnSeq = React.useRef(0)
  const initialAsked = React.useRef(false)
  const ask = React.useCallback(async (question: string) => {
    if (!question.trim()) return
    const id = Date.now() * 1000 + (turnSeq.current++ % 1000)
    setTurns((t) => [...t, { id, q: question }])
    setBusy(true)
    const r = await demoProvider.ask(question)
    setTurns((t) => t.map((x) => (x.id === id ? { ...x, r } : x)))
    setBusy(false)
  }, [])
  React.useEffect(() => {
    try {
      sessionStorage.setItem('dosafe-assistant', JSON.stringify(turns.slice(-20)))
    } catch {
      /* per-session convenience only */
    }
    endRef.current?.scrollIntoView({ behavior: 'smooth', block: 'end' })
  }, [turns])
  React.useEffect(() => {
    const initial = params.get('q')
    // Guard against StrictMode double-invocation asking the same question twice.
    if (initial && !initialAsked.current) {
      initialAsked.current = true
      ask(initial)
      setParams({}, { replace: true })
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [])
  return (
    <div className="space-y-4">
      <PageHeader title="DO SAFE Intelligence Assistant" icon={<Sparkles />} description="Ask questions about organizational risk. Answers are assembled from the demo dataset with supporting records, evidence and next actions." actions={turns.length > 0 && <Button variant="ghost" size="sm" onClick={() => setTurns([])}>Clear conversation</Button>} />
      <Callout tone="demo" icon={<FlaskConical />} title="Deterministic demo engine — not a live AI model">
        This prototype matches your question to a defined set of intents and runs structured queries against local demo records. Responses are not generated by a language model. The provider interface is designed so an LLM-backed implementation can replace it.
      </Callout>
      <div className="grid gap-5 xl:grid-cols-[1fr_300px]">
        <Card className="flex min-h-[560px] flex-col">
          <div className="flex-1 space-y-5 overflow-y-auto p-4">
            {turns.length === 0 && (
              <EmptyState icon={<Sparkles />} title="Ask about your risk posture" description="Pick a suggested question or type your own. Supported topics: critical vulnerabilities, KEV, application risk, vendors, AI configuration, shadow AI, overdue remediation, ALE, false positives, incidents and CVE lookups." />
            )}
            {turns.map((t) => (
              <div key={t.id} className="space-y-3">
                <div className="flex justify-end">
                  <div className="flex max-w-[80%] items-start gap-2 rounded-2xl rounded-tr-sm bg-violet-600/80 px-3.5 py-2 text-[13px] text-white">
                    {t.q}
                    <UserIcon className="mt-0.5 size-3.5 shrink-0 opacity-70" />
                  </div>
                </div>
                {!t.r ? (
                  <div className="flex items-center gap-2 text-xs text-muted">
                    <Loader2 className="size-4 animate-spin text-violet-700" /> Querying demo records…
                  </div>
                ) : (
                  <ResponseCard r={t.r} onAction={(to) => (to === '#search' ? setSearchOpen(true) : navigate(to))} />
                )}
              </div>
            ))}
            <div ref={endRef} />
          </div>
          <form
            onSubmit={(e) => {
              e.preventDefault()
              ask(q)
              setQ('')
            }}
            className="flex gap-2 border-t border-border p-3"
          >
            <input value={q} onChange={(e) => setQ(e.target.value)} placeholder="Ask about vulnerabilities, vendors, AI systems, financial risk…" aria-label="Ask a question" className="h-10 flex-1 rounded-lg border border-border bg-surface-2 px-3 text-sm focus:border-violet-500/60 focus:outline-none" disabled={busy} />
            <Button type="submit" disabled={busy || !q.trim()} size="lg">
              <Send /> Ask
            </Button>
          </form>
        </Card>
        <div className="space-y-4">
          <Section title="Suggested questions">
            <div className="space-y-1.5">
              {SUGGESTED_QUESTIONS.map((s) => (
                <button key={s} disabled={busy} onClick={() => ask(s)} className="block w-full rounded-lg bg-surface-2/70 px-3 py-2 text-left text-xs text-muted hover:bg-surface-2 hover:text-fg enabled:cursor-pointer">
                  {s}
                </button>
              ))}
            </div>
          </Section>
        </div>
      </div>
    </div>
  )
}

