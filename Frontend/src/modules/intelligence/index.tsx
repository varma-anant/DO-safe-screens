  if (isLoading || !data) return <LoadingState kpis={4} rows={8} />
  const kev = data.knowledge.filter((k) => k.type === 'CVE' && k.kev).map((k) => ({ k, affected: data.findings.filter((f) => f.cveId === k.externalId && isOpen(f.status)) })).sort((a, b) => b.affected.length - a.affected.length)
