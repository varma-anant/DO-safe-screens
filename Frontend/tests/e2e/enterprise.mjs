import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const base = process.env.PROTOTYPE_URL || 'http://127.0.0.1:5173'
const browser = await chromium.launch({headless:true})
const page = await browser.newPage({viewport:{width:1440,height:1000}})
page.setDefaultTimeout(15000)
const errors=[]
page.on('pageerror', e=>errors.push(e.message))
const visit=async path=>{await page.goto(base+path);await page.locator('main h1').first().waitFor()}
async function signIn(name) {
  await page.goto(base+'/login')
  await page.evaluate(()=>localStorage.clear())
  await page.reload()
  assert.equal(await page.locator('input').count(),0,'Login has no credential fields')
  assert.equal(await page.getByRole('button').count(),1,'Login has one SSO action')
  await page.getByRole('button',{name:'Sign in with SSO',exact:true}).click()
  await page.getByRole('button',{name:new RegExp(name)}).click()
  await page.getByRole('heading',{name:/Welcome back/}).waitFor()
}
